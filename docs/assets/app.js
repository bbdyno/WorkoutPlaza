const langSelect = document.getElementById("langSelect");
const toastEl = document.getElementById("toast");
let currentLang = "en";
let toastTimer = null;

function t(key) {
  return translations[currentLang]?.[key] ?? translations.en[key] ?? key;
}

function applyLanguage(lang) {
  currentLang = translations[lang] ? lang : "en";
  document.documentElement.lang = currentLang;

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    const value = t(key);
    if (value) {
      el.textContent = value;
    }
  });

  if (langSelect) {
    langSelect.value = currentLang;
  }
  localStorage.setItem("workoutplaza_lang", currentLang);
}

function showToast(message) {
  if (!toastEl) {
    return;
  }

  toastEl.textContent = message;
  toastEl.classList.add("show");

  if (toastTimer) {
    clearTimeout(toastTimer);
  }

  toastTimer = setTimeout(() => {
    toastEl.classList.remove("show");
  }, 1800);
}

async function copyText(text) {
  if (navigator.clipboard && window.isSecureContext) {
    await navigator.clipboard.writeText(text);
    return;
  }

  const temp = document.createElement("textarea");
  temp.value = text;
  temp.setAttribute("readonly", "");
  temp.style.position = "absolute";
  temp.style.left = "-9999px";
  document.body.appendChild(temp);
  temp.select();
  document.execCommand("copy");
  document.body.removeChild(temp);
}

function setupCopyButtons() {
  document.querySelectorAll(".copy-btn").forEach((button) => {
    button.addEventListener("click", async () => {
      const targetId = button.getAttribute("data-copy-target");
      const target = targetId ? document.getElementById(targetId) : null;
      if (!target) {
        return;
      }

      try {
        await copyText(target.textContent.trim());
        showToast(t("copy_done"));
      } catch (error) {
        showToast("Copy failed");
      }
    });
  });
}

function setupRevealAnimations() {
  const revealTargets = document.querySelectorAll(".reveal");
  if (revealTargets.length === 0) {
    return;
  }

  const observer = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          entry.target.classList.add("is-visible");
        }
      });
    },
    { threshold: 0.12 }
  );

  revealTargets.forEach((el) => observer.observe(el));
}

function setupLanguageSelector() {
  if (!langSelect) {
    return;
  }

  langSelect.addEventListener("change", (event) => {
    applyLanguage(event.target.value);
  });
}

function initializeLanguage() {
  const saved = localStorage.getItem("workoutplaza_lang");
  const browser = navigator.language?.split("-")[0] ?? "en";
  const initialLang = saved || (translations[browser] ? browser : "en");
  applyLanguage(initialLang);
}

setupLanguageSelector();
setupCopyButtons();
setupRevealAnimations();
initializeLanguage();
